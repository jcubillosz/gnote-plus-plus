// Historial del portapapeles: sondea NSPasteboard, guarda los últimos textos copiados y ofrece
// un selector (⌘⇧V) para pegarlos.
import SwiftUI
import AppKit
import Scintilla

final class ClipboardHistory: ObservableObject {
    static let limit = 30
    /// Tope por entrada: leer y guardar textos enormes en el hilo principal congelaría la UI.
    static let maxEntryBytes = 1_048_576
    /// Marcas de gestores de contraseñas y apps que copian datos que no deben quedar guardados.
    static let ignoredTypes: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    @Published private(set) var entries: [String] = []
    /// Largo en caracteres de cada entrada, calculado una vez al capturarla: contar 1 MB en cada
    /// redibujado del selector sería caro.
    private(set) var lengths: [String: Int] = [:]
    @Published var pickerVisible = false

    private var timer: Timer?
    private var observer: NSObjectProtocol?
    private var lastChangeCount = NSPasteboard.general.changeCount

    // MARK: lógica pura

    static func pushed(_ entries: [String], _ new: String, limit: Int) -> [String] {
        guard !new.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return entries }
        var result = entries.filter { $0 != new }
        result.insert(new, at: 0)
        return Array(result.prefix(limit))
    }

    static func shouldCapture(types: [String], byteCount: Int = 0) -> Bool {
        byteCount <= maxEntryBytes && !types.contains { ignoredTypes.contains($0) }
    }

    // MARK: sondeo

    func startPolling() {
        guard timer == nil else { return }
        // Se parte del contador actual: lo copiado antes de abrir la app no se registra.
        lastChangeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 1, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        observer = NotificationCenter.default.addObserver(
            forName: NSApplication.didBecomeActiveNotification, object: nil, queue: .main
        ) { [weak self] _ in self?.poll() }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        // Se recuerda el contador aunque se ignore el cambio, para no releerlo cada segundo.
        lastChangeCount = pb.changeCount
        // Los tipos primero: lo de un gestor de contraseñas no se lee ni una vez.
        let types = (pb.types ?? []).map(\.rawValue)
        guard Self.shouldCapture(types: types) else { return }
        // El tamaño se mide sobre los bytes, antes de construir el String.
        let byteCount = pb.data(forType: .string)?.count ?? 0
        guard Self.shouldCapture(types: types, byteCount: byteCount),
              let text = pb.string(forType: .string) else { return }
        let updated = Self.pushed(entries, text, limit: Self.limit)
        lengths = Dictionary(uniqueKeysWithValues: updated.map { ($0, lengths[$0] ?? $0.count) })
        entries = updated
    }

    func clear() {
        entries = []
        lengths = [:]
    }
}

/// Selector sobre el editor: filtro + lista con ↑↓, Enter pega, Esc cierra.
/// Observa el historial directamente: ContentView no se entera de `pickerVisible` (ObservableObject
/// anidado en TabsViewModel), así que ni mostrar/quitar el selector ni la exclusión mutua con el
/// QuickPanel pueden depender de que ContentView se vuelva a dibujar.
struct ClipboardHistoryPickerHost: View {
    @ObservedObject var history: ClipboardHistory
    let onShown: () -> Void
    let onPaste: (String) -> Void
    let onClose: (_ restoreFocus: Bool) -> Void

    var body: some View {
        Group {
            if history.pickerVisible {
                ClipboardHistoryPicker(history: history, onPaste: onPaste, onClose: onClose)
            }
        }
        .onChange(of: history.pickerVisible) { if $0 { onShown() } }
    }
}

struct ClipboardHistoryPicker: View {
    @ObservedObject var history: ClipboardHistory
    let onPaste: (String) -> Void
    /// `restoreFocus: false` cuando otra vista ya tomó el foco (ver FloatingPanelFocus).
    let onClose: (_ restoreFocus: Bool) -> Void

    @State private var filter = ""
    @State private var selection = 0
    @FocusState private var focused: Bool
    @State private var monitor: Any?
    @State private var focusTracker = FloatingPanelFocus()

    private var shown: [String] {
        let f = filter.trimmingCharacters(in: .whitespaces)
        return f.isEmpty ? history.entries : history.entries.filter { $0.localizedCaseInsensitiveContains(f) }
    }

    private func preview(_ s: String) -> String {
        let one = s.split(whereSeparator: \.isNewline).first.map(String.init) ?? s
        return String(one.prefix(120))
    }

    var body: some View {
        VStack(spacing: 6) {
            TextField(L("Filtrar historial"), text: $filter)
                .textFieldStyle(.roundedBorder)
                .focused($focused)
                .onSubmit { pasteSelected() }
                .onChange(of: filter) { _ in selection = 0 }
            ScrollViewReader { proxy in
                ScrollView {
                    LazyVStack(alignment: .leading, spacing: 0) {
                        ForEach(Array(shown.enumerated()), id: \.offset) { index, text in
                            HStack(spacing: 8) {
                                Text(preview(text))
                                    .lineLimit(1)
                                    .truncationMode(.tail)
                                Spacer(minLength: 0)
                                Text(L("\((history.lengths[text] ?? text.count).formatted()) car."))
                                    .font(.caption)
                                    .foregroundStyle(.secondary)
                                    .fixedSize()
                            }
                                .padding(.horizontal, 6).padding(.vertical, 3)
                                .frame(maxWidth: .infinity, alignment: .leading)
                                .background(index == selection ? Color.accentColor.opacity(0.35) : Color.clear)
                                .contentShape(Rectangle())
                                .onTapGesture { onPaste(text) }
                                .id(index)
                        }
                    }
                }
                .frame(height: 220)
                .onChange(of: selection) { proxy.scrollTo($0) }
            }
            HStack {
                Button(L("Vaciar historial")) { history.clear(); onClose(true) }
                    .disabled(history.entries.isEmpty)
                Spacer()
            }
        }
        .padding(8)
        .frame(width: 360)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 8))
        .shadow(radius: 6)
        .padding(.top, 8)
        .onAppear {
            focused = true
            // El campo de texto se queda con ↑↓ (mueve el cursor), y onKeyPress pide macOS 14:
            // un monitor local mientras el selector está abierto.
            if let m = monitor { NSEvent.removeMonitor(m) }
            monitor = NSEvent.addLocalMonitorForEvents(matching: .keyDown) { event in
                // Solo con el campo del selector activo y sin modificadores: ⌘↑/⇧↑ y las otras
                // ventanas o campos de la app conservan sus flechas.
                guard event.window === NSApp.keyWindow, focused,
                      (NSApp.keyWindow?.firstResponder as? NSTextView)?.isFieldEditor == true,
                      event.modifierFlags.intersection([.command, .shift, .option]).isEmpty
                else { return event }
                switch event.keyCode {
                case 53: onClose(true); return nil
                case 126: selection = max(0, selection - 1); return nil
                case 125: selection = min(max(0, shown.count - 1), selection + 1); return nil
                default: return event
                }
            }
        }
        .onDisappear { if let m = monitor { NSEvent.removeMonitor(m) }; monitor = nil }
        .onExitCommand { onClose(true) }
        .onChange(of: focused) { isFocused in
            if isFocused {
                focusTracker.capture()
                DispatchQueue.main.async { focusTracker.capture(onlyIfMissing: true) }
                return
            }
            // Un tick después, como QuickPanelView: el first responder nuevo ya está asentado.
            DispatchQueue.main.async {
                guard history.pickerVisible else { return }
                onClose(!focusTracker.takenElsewhere())
            }
        }
    }

    private func pasteSelected() {
        guard shown.indices.contains(selection) else { return }
        onPaste(shown[selection])
    }
}

/// Pega `text` como una sola acción de deshacer.
func pasteFromHistory(_ text: String, editor: ScintillaView) {
    _ = text.withCString { cstr in
        ScintillaView.directCall(editor, message: SCI_REPLACESEL, wParam: 0, lParam: sptr_t(bitPattern: UInt(bitPattern: cstr)))
    }
}
